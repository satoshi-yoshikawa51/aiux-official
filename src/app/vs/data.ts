export function getVsPair(slug: string): VsPair | undefined {
  return VS_PAIRS.find((p) => p.slug === slug);
}

/** 用語ページのサイドバー「くらべて理解する」用：この用語が登場する比較一覧 */
export function listVsForTerm(termSlug: string): VsPair[] {
  return VS_PAIRS.filter((p) => p.aSlug === termSlug || p.bSlug === termSlug);
}
