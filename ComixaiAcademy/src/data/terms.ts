/** 長い語から順に。「AIエージェント」を「エージェント」より先に当てるため */
export const TERMS_BY_LENGTH = [...TERMS].sort(
  (a, b) => Math.max(...lengths(b)) - Math.max(...lengths(a)),
);

function lengths(t: Term): number[] {
  return [t.word.length, ...(t.also ?? []).map((w) => w.length)];
}

/** その語で引く。見出し語でも別表記でも当たる */
export function getTerm(word: string): Term | undefined {
  return TERMS.find((t) => t.word === word || t.also?.includes(word));
}

/** サイトの用語集のURL。スラッグが無い語は null */
export function termUrl(t: Term): string | null {
  return t.slug ? `https://comixai.dev/glossary/${t.slug}` : null;
}
